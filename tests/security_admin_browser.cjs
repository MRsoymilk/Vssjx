// Real independent pages and breadcrumb navigation against an owned server.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright-core');
const [base,output]=process.argv.slice(2);
(async()=>{
    const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined});
    let checks=0;const check=v=>{assert.ok(v);checks++;};
    try {
        const page=await browser.newPage({viewport:{width:1280,height:1000}});
        const errors=[],requests=[];
        page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>requests.push(new URL(r.url()).pathname));
        await page.goto(base);
        await page.waitForFunction(()=>document.getElementById('health').textContent==='运行中');
        check(await page.locator('.section-nav a').count()===5);
        check(await page.locator('#breadcrumbs li').count()===1);
        check(await page.locator('#users-list,#announcement-form,#audit-list').count()===0);
        check(!requests.includes('/api/users') && !requests.includes('/api/audit'));
        await page.locator('.section-nav a[href="/announcements"]').click();
        await page.waitForFunction(()=>!document.getElementById('announcement-publish').disabled);
        check((await page.locator('#breadcrumbs').innerText()).includes('全局通知'));
        check(await page.locator('#cards,#users-list').count()===0);
        await page.locator('.section-nav a[href="/users"]').click();
        await page.waitForFunction(()=>document.getElementById('users-list').children.length>0);
        check(await page.locator('#users-title').isVisible());
        check((await page.locator('#users-status').innerText()).includes('总用户 54 个账号'));
        await page.locator('#users-q').fill('audit_alt');
        await page.locator('#users-search button[type=submit]').click();
        await page.waitForFunction(()=>document.getElementById('users-list').children.length===1);
        check((await page.locator('#users-list').innerText()).includes('audit_first'));
        check((await page.locator('#users-status').innerText()).includes('匹配 1 个'));
        await page.locator('#users-list .character-links a').filter({hasText:'audit_alt'}).click();
        await page.waitForFunction(()=>document.getElementById('user-selected-character').textContent.includes('audit_alt'));
        check((await page.locator('#breadcrumbs').innerText()).includes('audit_alt'));
        check(await page.locator('.selected-character').count()===1);
        check((await page.locator('#user-action').locator('..').innerText()).includes('全部角色'));
        await page.locator('#user-audit').click();
        await page.waitForFunction(()=>document.getElementById('audit-character').value!=='' && document.getElementById('audit-status').textContent.includes('已显示'));
        check((await page.locator('#breadcrumbs').innerText()).includes('audit_alt'));
        await page.locator('#breadcrumbs a').filter({hasText:'audit_alt'}).click();
        await page.waitForFunction(()=>document.getElementById('user-selected-character').textContent.includes('audit_alt'));
        // Deep links reload into the same selected role; breadcrumbs restore the list query.
        await page.reload();
        await page.waitForFunction(()=>document.getElementById('user-selected-character').textContent.includes('audit_alt'));
        check(await page.locator('.selected-character').count()===1);
        await page.goBack(); // Return to the role audit page.
        await page.locator('#breadcrumbs a[href="/users"]').click();
        await page.locator('#users-q').fill('audit_first');
        await page.locator('#users-search button[type=submit]').click();
        await page.waitForFunction(()=>document.getElementById('users-list').children.length===1);
        await page.locator('#users-list a').filter({hasText:'查看详情'}).click();
        await page.waitForFunction(()=>!document.getElementById('user-detail').hidden);
        check((await page.locator('#user-name').innerText()).includes('audit_first'));
        check((await page.locator('#user-characters').innerText()).includes('铜钱'));
        await page.locator('#breadcrumb-users').click();
        check(await page.locator('#users-q').inputValue()==='audit_first');
        await page.locator('#users-list a').filter({hasText:'查看详情'}).click();
        await page.waitForFunction(()=>!document.getElementById('user-execute').disabled);
        await page.locator('#user-audit').click();
        await page.waitForFunction(()=>document.getElementById('audit-list').children.length===100 && !document.getElementById('audit-character').disabled);
        const character=await page.locator('#audit-character option').nth(1).getAttribute('value');
        await page.locator('#audit-character').selectOption(character);
        await page.waitForFunction(()=>document.getElementById('audit-list').textContent.includes('pve.equip') && !document.getElementById('audit-list').textContent.includes('fixture.event'));
        check((await page.locator('#audit-list').textContent()).includes(character));
        await page.reload();
        await page.waitForFunction(()=>document.getElementById('audit-character').value!=='' && document.getElementById('audit-list').textContent.includes('pve.equip'));
        check(await page.locator('#audit-character').inputValue()===character);
        await page.locator('#audit-character').selectOption('');
        await page.waitForFunction(()=>document.getElementById('audit-list').children.length===100);
        await page.locator('#audit-more').click();
        await page.waitForFunction(()=>document.getElementById('audit-list').children.length>100);
        check((await page.locator('#audit-list').innerText()).includes('pve.equip'));
        await page.locator('#audit-outcome').selectOption('rejected');
        await page.waitForFunction(()=>document.getElementById('audit-list').textContent.includes('PVE_ID_CONFLICT') && !document.getElementById('audit-list').textContent.includes('fixture.event'));
        check(!(await page.locator('#audit-list').innerText()).includes('fixture.event'));
        await page.locator('#breadcrumbs a').filter({hasText:'audit_first'}).click();
        await page.goto(base+new URL(page.url()).pathname+'?character_id='+character);
        await page.waitForFunction(()=>!document.getElementById('user-execute').disabled);
        await page.locator('#user-action-kind').selectOption('disable');await page.locator('#user-reason').fill('浏览器回归验证');
        const sent=[];page.on('request',r=>{if(r.method()==='POST' && r.url().endsWith('/actions'))sent.push(r.postDataJSON());});
        await page.route('**/api/users/*/actions',async route=>{const response=await route.fetch();check(response.ok());await route.abort();},{times:1});
        page.once('dialog',d=>d.accept());await page.locator('#user-execute').click();
        await page.waitForFunction(()=>document.getElementById('user-action-status').textContent.includes('结果未确认') && !document.getElementById('user-execute').disabled);
        page.once('dialog',d=>d.accept());await page.locator('#user-execute').click();
        await page.waitForFunction(()=>document.getElementById('user-name').textContent.includes('已封禁') && !document.getElementById('user-execute').disabled);
        check((await page.locator('#user-action-status').innerText()).includes('已执行'));
        check(sent.length===2 && sent[0].operation_id===sent[1].operation_id);
        check(sent[0].character_id===character);
        await page.screenshot({path:`${output}/user-detail-desktop.png`,fullPage:true});
        await page.locator('#user-audit').click();
        await page.locator('#audit-outcome').selectOption('accepted');
        await page.waitForFunction(()=>document.getElementById('audit-list').textContent.includes('operator.disable'));
        check((await page.locator('#audit-list').textContent()).includes('selected_character'));
        await page.locator('#audit-list details').first().locator('summary').click();
        await page.screenshot({path:`${output}/audit-desktop.png`,fullPage:true});
        await page.setViewportSize({width:390,height:844});
        for(const path of ['/','/users?q=audit_first','/audit','/announcements']) {
            await page.goto(base+path);
            check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
            check(await page.locator('.breadcrumbs').isVisible());
        }
        await page.screenshot({path:`${output}/announcements-mobile.png`,fullPage:true});
        await page.goto(base+'/users?q=audit_first');
        await page.waitForFunction(()=>document.getElementById('users-list').children.length===1);
        const fixture=await (await page.request.get(base+'/api/users?q=audit_first')).json();
        fixture.users[0].username='<img src=x onerror="window.injected=true">';
        fixture.users[0].character_summaries[0].display_name='<svg onload="window.injected=true">';
        await page.route('**/api/users?*',r=>r.fulfill({json:fixture}));await page.locator('#users-refresh').click();
        await page.waitForFunction(()=>document.getElementById('users-list').textContent.includes('<img'));
        check(await page.locator('#users-list img,#users-list svg').count()===0);check(await page.evaluate(()=>!window.injected));
        check(errors.length===0);
        fs.writeFileSync(`${output}/browser.json`,JSON.stringify({checks,failures:0,browser:browser.version(),screenshots:3},null,2));
        console.log(`SECURITY BROWSER: ${checks} checks, 0 failures`);
    } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
