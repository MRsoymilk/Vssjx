const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright-core');
const [base, upload, output] = process.argv.slice(2);
assert(new URL(base).hostname === '127.0.0.1', 'Only an owned loopback fixture is accepted');
let browser, checks = 0;
const errors = [], requests = [];
const check = (value, message) => {assert.ok(value, message); checks++; console.log('PASS: ' + message);};
(async () => {
  try {
    fs.mkdirSync(output, {recursive: true});
    browser = await chromium.launch({headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined});
    const context = await browser.newContext({viewport: {width: 1440, height: 1100}});
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => {if (message.type() === 'error') errors.push(message.text());});
    page.on('request', request => requests.push(request.url()));
    await page.goto(base);
    await page.waitForFunction(() => document.querySelectorAll('.card').length === 8);
    check(await page.locator('.card strong').first().textContent() === '2', 'Portal totals use ingested events');
    check((await page.locator('#stats-panel').textContent()).includes('下载请求不等于下载完成'), 'Download counting limits are explicit');
    await page.getByRole('button', {name: '近 7 天', exact: true}).click();
    await page.waitForFunction(() => document.querySelectorAll('#daily tr').length === 7);
    check(await page.locator('#chart svg').count() === 1, 'Native trend chart and zero-filled daily rows render');
    const response = await context.request.get(base + '/api/export.csv?start=' + await page.locator('#start').inputValue() + '&end=' + await page.locator('#end').inputValue());
    check(response.status() === 200 && (await response.text()).includes('day_UTC+08:00'), 'CSV is available only on the private API');
    check((await page.locator('#collector').textContent()).includes('未运行或心跳已过期'), 'Offline fixture is not falsely shown as live collection');
    await page.screenshot({path: path.join(output, 'statistics-desktop.png'), fullPage: true});
    await page.setViewportSize({width: 390, height: 844});
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Statistics mobile layout does not overflow horizontally');
    await page.screenshot({path: path.join(output, 'statistics-mobile.png'), fullPage: true});
    await page.setViewportSize({width: 1440, height: 1100});
    await page.getByRole('button', {name: 'APK 文件', exact: true}).click();
    await page.waitForFunction(() => document.querySelectorAll('#apk-list tr').length === 2);
    check(await page.locator('#apk-list tr').filter({hasText: '旧版.apk'}).getByRole('button', {name: '删除旧版'}).isDisabled(), 'Current download cannot be deleted');
    check(await page.locator('#apk-list img').count() === 0 && (await page.locator('#apk-list').textContent()).includes('<img'), 'Untrusted APK display name is rendered as text, not HTML');
    await page.locator('#apk-file').setInputFiles(upload);
    await page.getByRole('button', {name: '上传 APK', exact: true}).click();
    await page.waitForFunction(() => document.querySelectorAll('#apk-list tr').length === 3);
    check((await page.locator('#notice').textContent()).includes('未自动发布'), 'Upload saves a new version without publishing');
    const current = page.locator('#apk-list tr').filter({hasText: 'new-preview.apk'});
    page.once('dialog', dialog => dialog.accept());
    await current.getByRole('button', {name: '设为当前', exact: true}).click();
    await page.waitForFunction(() => [...document.querySelectorAll('#apk-list tr')].some(row => row.textContent.includes('new-preview.apk') && row.textContent.includes('当前下载')));
    check(await current.getByRole('button', {name: '删除旧版'}).isDisabled(), 'Explicit publish changes current download protection');
    page.once('dialog', dialog => {assert.equal(dialog.type(), 'confirm'); dialog.accept();});
    await page.locator('#apk-list tr').filter({hasText: '<img'}).getByRole('button', {name: '删除旧版'}).click();
    await page.waitForFunction(() => document.querySelectorAll('#apk-list tr').length === 2);
    check(!(await page.locator('#apk-list').textContent()).includes('<img'), 'Confirmed old managed version is deleted');
    await page.screenshot({path: path.join(output, 'apks-desktop.png'), fullPage: true});
    await page.setViewportSize({width: 390, height: 844});
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'APK mobile layout stays within viewport');
    await page.screenshot({path: path.join(output, 'apks-mobile.png'), fullPage: true});
    check(requests.every(url => url.startsWith(base + '/')), 'Private UI has no third-party requests');
    check(errors.length === 0, 'No JavaScript or CSP errors: ' + errors.join('; '));
    fs.writeFileSync(path.join(output, 'requests.json'), JSON.stringify(requests, null, 2));
    console.log(`PORTAL ADMIN BROWSER: ${checks} checks, 0 failures`);
  } catch (error) {console.error(error); process.exitCode = 1;}
  finally {if (browser) await browser.close();}
})();
